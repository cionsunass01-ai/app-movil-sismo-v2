import 'recommendation_candidate.dart';

/// Overall high-level state of a recommendation query.
enum RecommendationOutcome {
  /// Optimal candidate identified with active, verified operational criteria.
  success,

  /// Candidates are physically reachable, but operational status is UNKNOWN (offline baseline).
  onlyUnverifiedAvailable,

  /// No recommendation can be safely provided to the citizen.
  noRecommendationAvailable,

  /// No walkable network path could be found to any candidate from citizen's location.
  allPointsUnreachable,

  /// All reachable candidate points are confirmed closed, empty, or blocked.
  allPointsClosed;

  String get displayName {
    switch (this) {
      case RecommendationOutcome.success:
        return 'Recomendación Operacional Disponible';
      case RecommendationOutcome.onlyUnverifiedAvailable:
        return 'Puntos Accesibles (Estado Operacional No Verificado)';
      case RecommendationOutcome.noRecommendationAvailable:
        return 'Sin Recomendación Disponible';
      case RecommendationOutcome.allPointsUnreachable:
        return 'Sin Rutas Peatonales Transitables';
      case RecommendationOutcome.allPointsClosed:
        return 'Todos los Puntos Cercanos Confirmados Cerrados';
    }
  }
}

/// The complete, multi-tiered output generated by the recommendation pipeline.
///
/// THREE DISTINCT UI OUTCOMES (Section 32):
/// 1. [recommended]: Best overall point balancing distance, freshness, and availability.
/// 2. [alternatives]: Viable alternative points if the citizen prefers another direction or less queue.
/// 3. [nearestByDistance]: Physically closest point via pedestrian network, even if status is unknown or sub-optimal.
///
/// NULLABLE RECOMMENDATION (Section 34):
/// [recommended] is strictly nullable! If all points are closed or unreachable,
/// the engine produces [RecommendationOutcome.noRecommendationAvailable] instead
/// of misleading the citizen.
class RecommendationResult {
  /// Overall outcome category.
  final RecommendationOutcome outcome;

  /// Top recommended point for the citizen (nullable if no point qualifies).
  final WaterPointCandidate? recommended;

  /// List of viable alternative points (e.g. 1 or 2 options).
  final List<WaterPointCandidate> alternatives;

  /// The physically closest walkable point by network distance (may differ from [recommended]).
  final WaterPointCandidate? nearestByDistance;

  /// Candidate points that were evaluated but excluded due to hard filters or closures.
  final List<WaterPointCandidate> excluded;

  /// Global notices or advisory warnings (e.g. "Datos con más de 2 horas de antigüedad").
  final List<String> warnings;

  /// Timestamp when this recommendation was computed.
  final DateTime generatedAt;

  /// Plain-language narrative summary for citizen display or voice assistants.
  final String narrativeExplanation;

  const RecommendationResult({
    required this.outcome,
    this.recommended,
    this.alternatives = const [],
    this.nearestByDistance,
    this.excluded = const [],
    this.warnings = const [],
    required this.generatedAt,
    required this.narrativeExplanation,
  });

  /// Factory for the case where all points are unreachable or offline graph has no path.
  factory RecommendationResult.noRecommendation({
    required RecommendationOutcome outcome,
    required DateTime generatedAt,
    required String reason,
    List<WaterPointCandidate> excluded = const [],
    List<String> warnings = const [],
  }) {
    return RecommendationResult(
      outcome: outcome,
      recommended: null,
      alternatives: const [],
      nearestByDistance: null,
      excluded: excluded,
      warnings: warnings,
      generatedAt: generatedAt,
      narrativeExplanation: reason,
    );
  }

  /// Whether a concrete primary recommendation is available for UI display.
  bool get hasRecommendation => recommended != null;

  Map<String, dynamic> toJson() => {
    'outcome': outcome.name,
    if (recommended != null) 'recommended': recommended!.toJson(),
    'alternatives': alternatives.map((a) => a.toJson()).toList(),
    if (nearestByDistance != null)
      'nearestByDistance': nearestByDistance!.toJson(),
    'excluded': excluded.map((e) => e.toJson()).toList(),
    'warnings': warnings,
    'generatedAt': generatedAt.toIso8601String(),
    'narrativeExplanation': narrativeExplanation,
  };
}
